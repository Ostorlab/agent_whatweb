# Behavioral check for the PlantUML Server plugin's product markers.
#
# Usage: ruby plugin_plantuml_check.rb <plugins directory>
# Exits 1 if a genuine PlantUML landing does not match or a lookalike does.

class Plugin
  @plugins = []

  class << self
    attr_reader :plugins

    def define(&block)
      plugin = new
      plugin.instance_eval(&block)
      @plugins << plugin
    end
  end

  def name(value = nil)
    @name = value unless value.nil?
    @name
  end

  def matches(value = nil)
    @matches = value unless value.nil?
    @matches || []
  end

  def method_missing(*_args, &_block)
    nil
  end

  def respond_to_missing?(*_args)
    true
  end
end

OFFICIAL = <<~HTML
  <!DOCTYPE html>
  <html lang="en"><head><title>PlantUML Server</title></head>
  <body><div class="app"><div class="footer">
  <p>PlantUML version 1.2026.10 (Wed Nov 11 11:23:55 UTC 2026)</p>
  </div></div></body></html>
HTML

TITLE_ONLY = <<~HTML
  <!DOCTYPE html>
  <html lang="en"><head><title>PlantUML Server</title></head>
  <body><div id="editor">Diagram source</div></body></html>
HTML

# The sample PNG a standalone -picoweb root redirects to. The tEXt chunk is
# plain ASCII in the binary body.
PICOWEB = "\x89PNG\r\n\x1a\n".b +
          "tEXtcopyleft\x00Generated by https://plantuml.com".b +
          "\x00\x00\x00\x00IEND\xaeB`\x82".b

OTHER_PNG = "\x89PNG\r\n\x1a\n".b +
            "tEXtSoftware\x00another renderer".b +
            "\x00\x00\x00\x00IEND\xaeB`\x82".b

DASHBOARD = <<~HTML
  <!DOCTYPE html>
  <html lang="en"><head><title>Operations dashboard</title></head>
  <body><p>Uptime and latency for the diagram service.</p></body></html>
HTML

PROSE = <<~HTML
  <!DOCTYPE html>
  <html lang="en"><head><title>Migration notes</title></head>
  <body><p>We replaced PlantUML with another renderer last year.</p></body></html>
HTML

plugins_directory = ARGV[0]
load File.join(plugins_directory, "plantuml.rb")
plugin = Plugin.plugins.last
matches = plugin.matches.select { |match| match[:search] == "body" }
header_matches = plugin.matches.select { |match| match[:search] == "headers[server]" }

def page_matches?(matches, page)
  matches.select { |match| match[:regexp] || match[:version] }.any? do |match|
    pattern = match[:regexp] || match[:version]
    page.match?(pattern)
  end
end

def version_of(matches, page)
  matches.each do |match|
    pattern = match[:version]
    next if pattern.nil?

    found = page.match(pattern)
    return found[1] if found
  end
  nil
end

failures = []
failures << "official PlantUML landing did not match" unless page_matches?(matches, OFFICIAL)
failures << "title-only landing did not match" unless page_matches?(matches, TITLE_ONLY)
failures << "standalone sample PNG did not match" unless page_matches?(matches, PICOWEB)
failures << "official release was not extracted" unless version_of(matches, OFFICIAL) == "1.2026.10"
failures << "plain dashboard matched" if page_matches?(matches, DASHBOARD)
failures << "prose mention matched" if page_matches?(matches, PROSE)
failures << "unrelated PNG matched" if page_matches?(matches, OTHER_PNG)
failures << "picoweb server header version was not extracted" unless version_of(header_matches, "PlantUML PicoWebServer 1.2026.10") == "1.2026.10"
failures << "unrelated server header matched" if page_matches?(header_matches, "nginx/1.2.3")

puts failures
exit(failures.empty? ? 0 : 1)
